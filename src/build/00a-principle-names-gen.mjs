// Build-time emitter for `src/shared/principle-names.gen.mjs`.
//
// A principle's name is the text of the H1 on its page under
// content/principles/, after the "P<n>: " prefix, so a scorecard and the
// principle page it links to name the principle the same way. The emitted
// module is committed so the Worker bundle and the type check need no build
// step; tests/principle-names-gen.test.ts re-reads the titles in memory and
// fails when a title changes and the module does not.

import { readdir, readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO_ROOT = join(fileURLToPath(import.meta.url), '..', '..', '..');
const PRINCIPLES_DIR = join(REPO_ROOT, 'content', 'principles');
const GEN_PATH = join(REPO_ROOT, 'src', 'shared', 'principle-names.gen.mjs');

const PAGE_FILE_RE = /^p(\d+)-.+\.md$/;

/**
 * Principle group code to name, read from the H1 of each principle page.
 * Throws when a page has no `# P<n>: ` H1, so a missing name cannot ship.
 */
export async function readPrincipleNames(dir = PRINCIPLES_DIR) {
  const files = (await readdir(dir)).filter((file) => PAGE_FILE_RE.test(file));
  files.sort((a, b) => Number(PAGE_FILE_RE.exec(a)[1]) - Number(PAGE_FILE_RE.exec(b)[1]));
  const names = {};
  for (const file of files) {
    const n = PAGE_FILE_RE.exec(file)[1];
    const source = await readFile(join(dir, file), 'utf8');
    const prefix = `# P${n}: `;
    const h1 = source.split('\n').find((line) => line.startsWith('# '));
    if (!h1?.startsWith(prefix) || !h1.slice(prefix.length).trim()) {
      throw new Error(`principle-names-gen: ${file} has no "${prefix}<name>" H1`);
    }
    names[`P${n}`] = h1.slice(prefix.length).trim();
  }
  return names;
}

// The quote style the repo formatter writes, so the committed file needs no reformat.
function quote(value) {
  if (value.includes("'") && !value.includes('"')) return `"${value}"`;
  return `'${value.replaceAll('\\', '\\\\').replaceAll("'", "\\'")}'`;
}

/** The module's bytes for these names. Pure, so the drift test can compare it with the committed file. */
export function renderPrincipleNamesModule(names) {
  const rows = Object.entries(names)
    .map(([group, name]) => `  ${group}: ${quote(name)},`)
    .join('\n');
  return `// GENERATED by src/build/00a-principle-names-gen.mjs. Do not edit.
// Each name is the H1 of content/principles/p<n>-*.md after its "P<n>: " prefix.
// Run \`bun run build\` to regenerate; tests/principle-names-gen.test.ts fails when this file is out of date.

/** Map of principle group code to the title of its principle page. */
export const PRINCIPLE_NAMES = {
${rows}
};
`;
}

export async function generatePrincipleNamesModule() {
  const content = renderPrincipleNamesModule(await readPrincipleNames());
  await writeFile(GEN_PATH, content);
  return { content, path: GEN_PATH };
}

export async function computeExpectedPrincipleNamesModule(dir = PRINCIPLES_DIR) {
  return { content: renderPrincipleNamesModule(await readPrincipleNames(dir)), path: GEN_PATH };
}
